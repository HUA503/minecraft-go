// GetCJKGlyph returns the 11x11 bitmap for a rune, or generates a clean fallback.
func GetCJKGlyph(ch rune) [11]uint16 {
	if g, ok := cjkGlyphs11x11[ch]; ok {
		return g
	}
	// Deterministic clean fallback ideogram frame
	h := uint16(ch & 0x7F)
	return [11]uint16{
		0x7FE, 0x402, 0x492, 0x402,
		0x402 ^ (h << 2), 0x7FE,
		0x402 ^ (h << 1), 0x402,
		0x492, 0x402, 0x7FE,
	}
}
